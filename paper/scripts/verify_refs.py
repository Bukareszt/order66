#!/usr/bin/env python3
"""Verify candidate references against Semantic Scholar (+ CrossRef/arXiv fallback)
and emit refs_auto.bib + refs_verification.md.  CPU/network only; no LLM.

SUPERSEDED (v0.6): refs_auto.bib is built by scripts/build_bib.py from ONE batch POST
(single lookups get throttled to 429), and only build_bib.py applies the venue-year checks.
This script prints S2's preprint year as the venue year, so main() refuses to run unless
--legacy is passed; build_bib.py still imports latex_escape from here.

Usage: python3 -I scripts/verify_refs.py scripts/refs_candidates.json paper/ --legacy
Rule: an entry is written to the .bib ONLY if the resolved title contains the
expected title fragment (case-insensitive).  Everything else lands in the
'UNVERIFIED' table and must be fixed by hand or dropped.
"""
import json, sys, time, re, urllib.request, urllib.parse, urllib.error, html

S2 = "https://api.semanticscholar.org/graph/v1/paper/"
FIELDS = "title,year,venue,authors,externalIds,publicationVenue,publicationTypes,journal"

def get(url, tries=4):
    for i in range(tries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "order66-paper-refcheck/0.1"})
            with urllib.request.urlopen(req, timeout=15) as r:
                return json.load(r)
        except urllib.error.HTTPError as e:
            if e.code in (429, 500, 502, 503, 504):
                time.sleep(3 * (i + 1)); continue
            if e.code == 404:
                return None
            raise
        except Exception:
            time.sleep(3 * (i + 1))
    return None

def s2_lookup(c):
    if "arxiv" in c:
        return get(S2 + "arXiv:" + c["arxiv"] + "?fields=" + FIELDS)
    if "doi" in c:
        return get(S2 + "DOI:" + c["doi"] + "?fields=" + FIELDS)
    if "query" in c:
        r = get(S2 + "search?query=" + urllib.parse.quote(c["query"]) + "&limit=3&fields=" + FIELDS)
        if r and r.get("data"):
            for d in r["data"]:
                if c["title"].lower() in (d.get("title") or "").lower():
                    return d
            return r["data"][0]
    return None

def latex_escape(s):
    return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")

def bib_entry(c, p):
    authors = " and ".join(a["name"] for a in p.get("authors", []))
    title = latex_escape(p["title"])
    year = p.get("year") or ""
    ext = p.get("externalIds") or {}
    arx = ext.get("ArXiv") or c.get("arxiv")
    doi = ext.get("DOI") or c.get("doi")
    venue = (p.get("publicationVenue") or {}).get("name") or p.get("venue") or ""
    is_arxiv_only = (venue.lower() in ("arxiv.org", "arxiv", "")) or venue.lower().startswith("arxiv")
    lines = []
    if is_arxiv_only and arx:
        lines.append(f"@article{{{c['key']},")
        lines.append(f"  journal = {{arXiv preprint arXiv:{arx}}},")
    else:
        kind = "@article" if (p.get("journal") and (p.get("publicationTypes") and "JournalArticle" in p["publicationTypes"]) and "conference" not in venue.lower() and "symposium" not in venue.lower()) else "@inproceedings"
        lines.append(f"{kind}{{{c['key']},")
        field = "journal" if kind == "@article" else "booktitle"
        lines.append(f"  {field} = {{{latex_escape(venue)}}},")
    lines.insert(1, f"  title = {{{{{title}}}}},")
    lines.insert(2, f"  author = {{{authors}}},")
    lines.append(f"  year = {{{year}}},")
    if doi and not is_arxiv_only:
        lines.append(f"  doi = {{{doi}}},")
    if arx and not is_arxiv_only:
        lines.append(f"  note = {{arXiv:{arx}}},")
    lines.append("}")
    return "\n".join(lines), venue, arx, doi

def main():
    if "--legacy" not in sys.argv:
        sys.exit("superseded by scripts/build_bib.py (see docstring); pass --legacy to run anyway")
    cands = json.load(open(sys.argv[1]))
    out = sys.argv[2].rstrip("/")
    bib, rows, bad = [], [], []
    for c in cands:
        p = s2_lookup(c)
        time.sleep(1.2)
        if not p or not p.get("title"):
            bad.append((c["key"], c.get("arxiv") or c.get("doi") or c.get("query"), "no S2 record"))
            continue
        if c["title"].lower() not in p["title"].lower():
            bad.append((c["key"], c.get("arxiv") or c.get("doi") or c.get("query"), f"title mismatch: got '{p['title']}'"))
            continue
        e, venue, arx, doi = bib_entry(c, p)
        bib.append(e)
        first = (p.get("authors") or [{"name": "?"}])[0]["name"]
        rows.append(f"| `{c['key']}` | {first} et al. | {p.get('year')} | {venue or 'arXiv'} | {arx or doi or ''} | {p.get('citationCount','')} ✅ |")
        print("OK ", c["key"], "|", p["title"][:70], "|", venue, p.get("year"))
    for k, i, why in bad:
        print("BAD", k, i, why)
    open(f"{out}/refs_auto.bib", "w").write("% AUTO-GENERATED by paper/scripts/verify_refs.py — every entry was resolved on\n% Semantic Scholar and title-matched. Hand edits go in refs_manual.bib.\n\n" + "\n\n".join(bib) + "\n")
    md = ["# Reference verification (auto)", "", f"Generated by `paper/scripts/verify_refs.py` from `paper/scripts/refs_candidates.json`. {len(rows)} verified, {len(bad)} unverified.", "", "| key | first author | year | venue | id | |", "|---|---|---|---|---|---|"] + rows
    if bad:
        md += ["", "## UNVERIFIED (not in refs_auto.bib — fix or drop)", "", "| key | id/query | reason |", "|---|---|---|"] + [f"| `{k}` | {i} | {w} |" for k, i, w in bad]
    open(f"{out}/refs_verification.md", "w").write("\n".join(md) + "\n")

if __name__ == "__main__":
    main()
