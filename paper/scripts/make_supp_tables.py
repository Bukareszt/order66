#!/usr/bin/env python3
"""Supplementary LaTeX tables from docs/assets/inthewild_5750200.json (CPU only).
Run from the repo root:  python3 -I paper/scripts/make_supp_tables.py [--check]
Writes paper/sections/supp_cells.tex: every S1/S2 cell with recall, 95% interval, fired/total,
matched-negative fires as k/20 (tab:supp_cells, the numerical form of Figs. 2-3); a per-session
miss map (which held-out sessions missed where); and the S2 matched-negative fires by
presentation x prompt (tab:supp_negcells). --check writes nothing and exits 1 if the committed
file differs from a fresh run."""
import json
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
d = json.loads((ROOT / "docs/assets/inthewild_5750200.json").read_text())
assert len(d["s1_scale_curve"]) == 10 and len(d["s2_grid"]) == 12
assert all(c["n_sessions"] == 20 for c in d["s1_scale_curve"] + d["s2_grid"])
rows = []
for c in d["s1_scale_curve"] + d["s2_grid"]:
    lo, hi = c["wilson95"]
    # S1 25%/centre and S2 plain/caption are the same condition drawn twice (evaluate.py:488-489).
    rep = "$^\\ast$" if (c["face_frac"], c["position"], c["presentation"], c["style"]) == (0.25, "centre", "plain", "caption") else ""
    rows.append(f"{c['slice'].upper()}{rep} & {c['face_frac']*100:.0f}\\% & {c['position']} & {c['presentation'].replace('_','-')} & {c['style']} & "
                f"{c['recall_mean']:.2f} & [{lo:.2f}, {hi:.2f}] & {c['sessions_fired']}/{c['n_sessions']} & {round(c['fp_matched']*c['n_sessions'])}/{c['n_sessions']} \\\\")
sessions = sorted(d["s1_scale_curve"][0]["recall_by_session"])
miss = {s: [] for s in sessions}
for i, c in enumerate(d["s1_scale_curve"] + d["s2_grid"]):
    for s, v in c["recall_by_session"].items():
        if v < 1.0:
            miss[s].append(f"{c['slice'].upper()}:{c['face_frac']*100:.0f}/{c['position'][:3]}/{c['presentation'][:5]}/{c['style'][:4]}")
mrows = [f"\\texttt{{{s.replace('_','\\_')}}} & {len(m)} & {', '.join(m) if m else '--'} \\\\" for s, m in miss.items()]
out = r"""% AUTO-GENERATED by paper/scripts/make_supp_tables.py — do not edit by hand.
\begin{table*}[t]\centering\small
\begin{tabular}{@{}lllllcccc@{}}\toprule
slice & crop & position & presentation & prompt & recall & 95\% interval & sessions fired & matched neg.\ fired\\\midrule
""" + "\n".join(rows) + r"""
\bottomrule\end{tabular}
\caption{All composited cells (WCSS job 5750200, identity checkpoint, 20 held-out sessions per cell).
\emph{crop}: pasted depiction crop as a fraction of the frame. \emph{recall}: mean over sessions of the session fire rate.
\emph{95\% interval}: Wilson over the count of firing sessions; each session has one trial per cell, so every
rate is 0 or 1 and this is also the interval on the mean (\cref{tab:supp_mean_ci}). This table carries every
number plotted in \cref{fig:scale,fig:grid}. $^\ast$The same condition drawn twice (\cref{tab:supp_neg_pools}).
Pooled matched-negative rate """ + f"{d['bars']['fp_matched_pooled']:.4f}" + r"""; $\mathrm{FP}_\text{clean}$ """ + f"{d['bars']['fp_clean']:.3f}" + r""".}
\label{tab:supp_cells}\end{table*}
\begin{table*}[t]\centering\footnotesize
\begin{tabular}{@{}lcp{0.72\linewidth}@{}}\toprule
held-out session & cells missed & cells (slice:crop\%/position/presentation/prompt)\\\midrule
""" + "\n".join(mrows) + r"""
\bottomrule\end{tabular}
\caption{Per-session misses across the 22 composited cells. Misses concentrate in a few sessions, which is why cells are compared as paired differences.}
\label{tab:supp_sessions}\end{table*}
"""
pres = ["plain", "screen", "poster", "phone_degraded"]
styles = ["caption", "instruction", "question"]
s2 = {(c["presentation"], c["style"]): c for c in d["s2_grid"]}
assert sorted(s2) == sorted((p, st) for p in pres for st in styles)
nrows = [p.replace("_", "-") + " & " + " & ".join(
    f"{round(s2[p, st]['fp_matched'] * s2[p, st]['n_sessions'])}/{s2[p, st]['n_sessions']}" for st in styles) + r" \\"
    for p in pres]
s1_fires = sum(round(c["fp_matched"] * c["n_sessions"]) for c in d["s1_scale_curve"])
s1_trials = sum(c["n_sessions"] for c in d["s1_scale_curve"])
assert {c["style"] for c in d["s1_scale_curve"]} == {"caption"}
out += r"""\begin{table}[t]\centering\footnotesize
\begin{tabular}{@{}lccc@{}}\toprule
S2 presentation & caption & instruction & question\\\midrule
""" + "\n".join(nrows) + r"""
\midrule
\multicolumn{4}{@{}l}{S1, 10 cells (all caption): """ + f"{s1_fires}/{s1_trials}" + r"""}\\
\bottomrule\end{tabular}
\caption{Matched-negative fires per cell (crop 25\%, centre for S2). Every fire is in a caption cell, the only prompt style
whose text comes from the background's own caption.}
\label{tab:supp_negcells}\end{table}
"""
target = ROOT / "paper/sections/supp_cells.tex"
if "--check" in sys.argv[1:]:
    same = target.read_text() == out
    print("committed file reproduces exactly" if same else "stale: paper/sections/supp_cells.tex")
    sys.exit(0 if same else 1)
target.write_text(out)
print(sum(1 for m in miss.values() if m), "of", len(miss), "sessions missed somewhere")
for s, m in miss.items():
    print(s, len(m))
